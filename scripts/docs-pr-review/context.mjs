/**
 * Deterministic context for the docs PR reviewer.
 *
 * Everything in this file is plain code, no model calls. It answers the
 * questions that have a checkable answer, so the model never has to guess them:
 *
 *   - Is a changed page live in the navigation, redirected away, or orphaned?
 *   - Where does the page sit in llms-full.txt, and which pages sit next to it?
 *   - Do internal links added by the PR resolve to live pages?
 *
 * All inputs are read from the DEFAULT-BRANCH checkout (docs.json,
 * llms-full.txt, neighbor pages). Nothing here reads or executes PR code; PR
 * file contents arrive as strings from the GitHub API and are treated as data.
 */

import fs from "node:fs";
import path from "node:path";

const DOCS_SITE = "https://docs.base.org/";

/** Pages generated by repo tooling; reviewing them adds noise, not signal. */
export const GENERATED_FILES = new Set([
  "docs/llms.txt",
  "docs/llms-full.txt",
  "docs/AGENTS.md",
]);

/** True for a documentation page this reviewer should look at. */
export function isReviewablePage(filename) {
  if (GENERATED_FILES.has(filename)) return false;
  return /^docs\/.+\.(md|mdx)$/.test(filename);
}

/** docs/get-started/connect-to-base.mdx -> get-started/connect-to-base */
export function routeForFile(filename) {
  return filename
    .replace(/^docs\//, "")
    .replace(/\.(md|mdx)$/, "")
    .replace(/\/index$/, "");
}

function normalizeRoute(r) {
  return String(r || "")
    .trim()
    .replace(/^https?:\/\/docs\.base\.org/, "")
    .replace(/[#?].*$/, "")
    .replace(/\.md$/, "")
    .replace(/^\/+|\/+$/g, "");
}

/** Every page route referenced anywhere in docs.json `navigation`. */
export function collectNavRoutes(navigation) {
  const routes = new Set();
  const walk = (node) => {
    if (typeof node === "string") {
      routes.add(normalizeRoute(node));
    } else if (Array.isArray(node)) {
      node.forEach(walk);
    } else if (node && typeof node === "object") {
      for (const [key, value] of Object.entries(node)) {
        // Only page lists hold routes; skip labels, icons, hrefs to other sites.
        if (key === "pages" || key === "groups" || key === "tabs" || key === "anchors" || key === "dropdowns" || key === "versions" || key === "languages" || key === "menu") {
          walk(value);
        }
      }
    }
  };
  walk(navigation);
  return routes;
}

/** Exact-source redirect map (wildcard sources are matched by prefix). */
export function buildRedirects(redirects = []) {
  const exact = new Map();
  const wildcard = [];
  for (const r of redirects) {
    if (!r || typeof r.source !== "string" || typeof r.destination !== "string") continue;
    const src = r.source.trim();
    const m = src.match(/^(.*?)\/:[A-Za-z0-9_]+\*$/);
    if (m) wildcard.push({ prefix: normalizeRoute(m[1]), destination: r.destination });
    else exact.set(normalizeRoute(src), r.destination);
  }
  return { exact, wildcard };
}

function lookupRedirect(redirects, route) {
  if (redirects.exact.has(route)) return normalizeRoute(redirects.exact.get(route));
  for (const w of redirects.wildcard) {
    if (route === w.prefix || route.startsWith(`${w.prefix}/`)) {
      return normalizeRoute(w.destination.replace(/\/:[A-Za-z0-9_]+\*$/, ""));
    }
  }
  return null;
}

/**
 * Status of a route on the live site.
 *   live          — listed in docs.json navigation
 *   redirected    — a redirect sends readers elsewhere (followed up to 5 hops)
 *   not-in-nav    — neither listed nor redirected (orphan; readers cannot find it)
 */
export function pageStatus(route, navRoutes, redirects) {
  if (navRoutes.has(route)) return { status: "live", route };
  let current = route;
  const hops = [];
  for (let i = 0; i < 5; i++) {
    const next = lookupRedirect(redirects, current);
    if (!next || next === current || hops.includes(next)) break;
    hops.push(next);
    current = next;
    if (navRoutes.has(current)) break;
  }
  if (hops.length) {
    return {
      status: "redirected",
      route,
      destination: current,
      destinationLive: navRoutes.has(current),
    };
  }
  return { status: "not-in-nav", route };
}

/**
 * Parse the autogenerated page index in llms-full.txt into entries with the
 * heading path they sit under (e.g. ["Get Started", "Quickstart"]).
 */
export function parseLlmsIndex(text) {
  const start = text.indexOf("<!-- LLMS_AUTOGEN_START -->");
  const end = text.indexOf("<!-- LLMS_AUTOGEN_END -->");
  const body = start >= 0 ? text.slice(start, end > start ? end : undefined) : text;
  const entries = [];
  const stack = [];
  const entryRe = /^\s*-\s+\[([^\]]+)\]\((https?:\/\/docs\.base\.org\/[^)\s]*)\)\s*:?\s*(.*)$/;
  for (const line of body.split("\n")) {
    const h = line.match(/^(#{2,6})\s+(.+?)\s*$/);
    if (h) {
      const depth = h[1].length - 2; // "##" is depth 0
      stack.length = depth;
      stack[depth] = h[2];
      continue;
    }
    const e = line.match(entryRe);
    if (e) {
      entries.push({
        title: e[1],
        route: normalizeRoute(e[2]),
        description: e[3].trim(),
        headings: stack.filter(Boolean),
      });
    }
  }
  return entries;
}

/** Index location and siblings (same heading path) for a route. */
export function locateInIndex(entries, route, maxNeighbors = 6) {
  const entry = entries.find((e) => e.route === route);
  if (!entry) return { found: false, route, neighbors: [] };
  const key = entry.headings.join(" > ");
  const neighbors = entries
    .filter((e) => e.route !== route && e.headings.join(" > ") === key)
    .slice(0, maxNeighbors);
  return { found: true, route, entry, section: key, neighbors };
}

/** Internal links on lines the PR added. */
export function extractAddedInternalLinks(patch = "") {
  const links = new Set();
  for (const line of patch.split("\n")) {
    if (!line.startsWith("+") || line.startsWith("+++")) continue;
    for (const m of line.matchAll(/\]\((\/[^)\s]+)\)/g)) links.add(m[1]);
    for (const m of line.matchAll(/href=["'](\/[^"'\s]+)["']/g)) links.add(m[1]);
  }
  return [...links];
}

/** Resolve a page route to a file in the default-branch checkout. */
export function localFileForRoute(repoRoot, route) {
  const candidates = [`${route}.mdx`, `${route}.md`, `${route}/index.mdx`, `${route}/index.md`];
  for (const c of candidates) {
    const p = path.join(repoRoot, "docs", c);
    if (fs.existsSync(p)) return { file: `docs/${c}`, abs: p };
  }
  return null;
}

export function readCapped(abs, maxChars) {
  try {
    const text = fs.readFileSync(abs, "utf8");
    return text.length > maxChars ? `${text.slice(0, maxChars)}\n…[truncated]` : text;
  } catch {
    return null;
  }
}

/**
 * Load the site model once from the default-branch checkout.
 */
export function loadSite(repoRoot) {
  const docsJson = JSON.parse(fs.readFileSync(path.join(repoRoot, "docs/docs.json"), "utf8"));
  const llmsFull = fs.readFileSync(path.join(repoRoot, "docs/llms-full.txt"), "utf8");
  return {
    navRoutes: collectNavRoutes(docsJson.navigation),
    redirects: buildRedirects(docsJson.redirects),
    index: parseLlmsIndex(llmsFull),
  };
}

/**
 * Build the per-file fact sheet the prompt and the summary comment both use.
 *
 * @param {object} opts
 * @param {string} opts.repoRoot     default-branch checkout root
 * @param {object} opts.site         result of loadSite()
 * @param {Array}  opts.files        [{ filename, status, patch, headContent }]
 * @param {object} opts.limits       { neighborChars, destinationChars, maxNeighbors }
 */
export function buildFileFacts({ repoRoot, site, files, limits = {} }) {
  const neighborChars = limits.neighborChars ?? 4000;
  const destinationChars = limits.destinationChars ?? 20000;
  const maxNeighbors = limits.maxNeighbors ?? 6;

  return files.map((f) => {
    const route = routeForFile(f.filename);
    const placement = pageStatus(route, site.navRoutes, site.redirects);
    // For a redirected page, the live page is where readers actually land, so
    // it is the page whose neighbors matter.
    const indexRoute = placement.status === "redirected" ? placement.destination : route;
    const location = locateInIndex(site.index, indexRoute, maxNeighbors);

    const neighbors = location.neighbors.map((n) => {
      const local = localFileForRoute(repoRoot, n.route);
      return {
        title: n.title,
        route: n.route,
        description: n.description,
        file: local?.file ?? null,
        excerpt: local ? readCapped(local.abs, neighborChars) : null,
      };
    });

    let destinationPage = null;
    if (placement.status === "redirected") {
      const local = localFileForRoute(repoRoot, placement.destination);
      destinationPage = {
        route: placement.destination,
        file: local?.file ?? null,
        content: local ? readCapped(local.abs, destinationChars) : null,
      };
    }

    const links = extractAddedInternalLinks(f.patch).map((href) => {
      const r = normalizeRoute(href);
      const s = pageStatus(r, site.navRoutes, site.redirects);
      const exists = Boolean(localFileForRoute(repoRoot, r));
      let verdict;
      if (s.status === "live") verdict = "live";
      else if (s.status === "redirected") verdict = `redirects to /${s.destination}`;
      else verdict = exists ? "page exists but is not in navigation" : "no such page";
      return { href, verdict };
    });

    return {
      filename: f.filename,
      changeType: f.status,
      route,
      placement,
      index: location.found
        ? { section: location.section, title: location.entry.title, description: location.entry.description }
        : null,
      neighbors,
      destinationPage,
      links,
    };
  });
}

export const _internals = { normalizeRoute, lookupRedirect, DOCS_SITE };
